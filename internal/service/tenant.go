// ---------- Tenants & members ----------

func (s *Service) ListTenants(ctx context.Context, p *Principal) ([]domain.TenantWithRole, error) {
	return s.Store.Memberships().ListTenantsForUser(ctx, p.User.ID)
}

// CreateOrganization creates a shared tenant owned by the caller.
func (s *Service) CreateOrganization(ctx context.Context, p *Principal, name string) (*domain.Tenant, error) {
	if p.TokenID != "" {
		return nil, domain.Forbidden("access tokens cannot create workspaces")
	}
	name = strings.TrimSpace(name)
	if name == "" {
		return nil, domain.Invalid("name is required")
	}
	var t *domain.Tenant
	err := s.Store.WithTx(ctx, func(tx port.Store) error {
		slug, err := uniqueTenantSlug(ctx, tx, name)
		if err != nil {
			return err
		}
		t = &domain.Tenant{ID: newID(), Name: name, Slug: slug, Kind: domain.TenantOrganization, OwnerID: p.User.ID, CreatedAt: now()}
		if err := tx.Tenants().Create(ctx, t); err != nil {
			return err
		}
		return tx.Memberships().Upsert(ctx, &domain.Membership{TenantID: t.ID, UserID: p.User.ID, Role: domain.RoleOwner, CreatedAt: now()})
	})
	return t, err
}

func (s *Service) ListMembers(ctx context.Context, sc *Scope) ([]domain.MemberView, error) {
	if err := sc.can(domain.RoleViewer, false); err != nil {
		return nil, err
	}
	return s.Store.Memberships().ListMembers(ctx, sc.TenantID())
}

// AddMember adds an existing user (by email) to an organization tenant.
func (s *Service) AddMember(ctx context.Context, sc *Scope, email string, role domain.Role) (*domain.MemberView, error) {
	if err := sc.can(domain.RoleAdmin, true); err != nil {
		return nil, err
	}
	if sc.Tenant.Kind == domain.TenantPersonal {
		return nil, domain.Invalid("personal workspaces cannot have members; create an organization")
	}
	if !role.Valid() || role == domain.RoleOwner {
		return nil, domain.Invalid("role must be admin, member or viewer")
	}
	if role == domain.RoleAdmin && sc.Role != domain.RoleOwner {
		return nil, domain.Forbidden("only owners can add admins")
	}
	u, err := s.Store.Users().GetByEmail(ctx, strings.ToLower(strings.TrimSpace(email)))
	if err != nil {
		if domain.KindOf(err) == domain.KindNotFound {
			return nil, domain.NotFound("no user registered with that email")
		}
		return nil, err
	}
	if existing, err := s.Store.Memberships().Get(ctx, sc.TenantID(), u.ID); err == nil && existing.Role == domain.RoleOwner {
		return nil, domain.Invalid("cannot change the owner's role")
	}
	if err := s.Store.Memberships().Upsert(ctx, &domain.Membership{TenantID: sc.TenantID(), UserID: u.ID, Role: role, CreatedAt: now()}); err != nil {
		return nil, err
	}
	return &domain.MemberView{UserID: u.ID, Email: u.Email, Name: u.Name, Role: role}, nil
}

func (s *Service) RemoveMember(ctx context.Context, sc *Scope, userID string) error {
	if err := sc.can(domain.RoleAdmin, true); err != nil {
		return err
	}
	m, err := s.Store.Memberships().Get(ctx, sc.TenantID(), userID)
	if err != nil {
		return err
	}
	if m.Role == domain.RoleOwner {
		return domain.Invalid("the owner cannot be removed")
	}
	return s.Store.Memberships().Delete(ctx, sc.TenantID(), userID)
}

// ---------- Cloud (AWS) connection ----------

type AWSConnectionInput struct {
	Region   string `json:"region"`
	RoleARN  string `json:"role_arn"`
	KMSKeyID string `json:"kms_key_id"`
}

func (s *Service) GetAWSConnection(ctx context.Context, sc *Scope) (*domain.CloudConnection, error) {
	if err := sc.can(domain.RoleAdmin, false); err != nil {
		return nil, err
	}
	return s.Store.Clouds().Get(ctx, sc.TenantID(), domain.CloudAWS)
}

// SetAWSConnection stores the role Vaulty assumes in the tenant's AWS account.
// The external id is generated by Vaulty (confused-deputy protection) and must
// be added to the role's trust policy.
func (s *Service) SetAWSConnection(ctx context.Context, sc *Scope, in AWSConnectionInput) (*domain.CloudConnection, error) {
	if err := sc.can(domain.RoleAdmin, true); err != nil {
		return nil, err
	}
	if in.Region == "" || !strings.HasPrefix(in.RoleARN, "arn:aws") || !strings.Contains(in.RoleARN, ":role/") {
		return nil, domain.Invalid("region and a valid IAM role ARN are required")
	}
	if err := s.ensureNoSecrets(ctx, sc); err != nil {
		return nil, err
	}
	c, err := s.Store.Clouds().Get(ctx, sc.TenantID(), domain.CloudAWS)
	if err != nil && domain.KindOf(err) != domain.KindNotFound {
		return nil, err
	}
	if c == nil {
		c = &domain.CloudConnection{TenantID: sc.TenantID(), Provider: domain.CloudAWS, ExternalID: "vaulty-" + randomToken("")[:32], CreatedAt: now()}
	}
	c.Region, c.RoleARN, c.KMSKeyID = in.Region, in.RoleARN, in.KMSKeyID
	c.Status, c.LastError, c.VerifiedAt, c.UpdatedAt = "pending", "", nil, now()
	if err := s.Store.Clouds().Upsert(ctx, c); err != nil {
		return nil, err
	}
	return c, nil
}

// VerifyAWSConnection assumes the role and checks Secrets Manager / KMS access.
func (s *Service) VerifyAWSConnection(ctx context.Context, sc *Scope) (*domain.CloudConnection, error) {
	if err := sc.can(domain.RoleAdmin, true); err != nil {
		return nil, err
	}
	c, err := s.Store.Clouds().Get(ctx, sc.TenantID(), domain.CloudAWS)
	if err != nil {
		return nil, err
	}
	if s.Verifier == nil {
		return nil, domain.Unavailable(nil, "AWS verification is not available on this server")
	}
	vctx, cancel := context.WithTimeout(ctx, 20*time.Second)
	defer cancel()
	if verr := s.Verifier.Verify(vctx, c); verr != nil {
		c.Status, c.LastError = "error", verr.Error()
	} else {
		t := now()
		c.Status, c.LastError, c.VerifiedAt = "verified", "", &t
	}
	c.UpdatedAt = now()
	if err := s.Store.Clouds().Upsert(ctx, c); err != nil {
		return nil, err
	}
	return c, nil
}

func (s *Service) DeleteAWSConnection(ctx context.Context, sc *Scope) error {
	if err := sc.can(domain.RoleAdmin, true); err != nil {
		return err
	}
	if err := s.ensureNoSecrets(ctx, sc); err != nil {
		return err
	}
	return s.Store.Clouds().Delete(ctx, sc.TenantID(), domain.CloudAWS)
}

// Secrets live in the account configured when they were written, so the
// storage location cannot change while the tenant has secrets.
func (s *Service) ensureNoSecrets(ctx context.Context, sc *Scope) error {
	projects, err := s.Store.Projects().List(ctx, sc.TenantID())
	if err != nil {
		return err
	}
	for _, p := range projects {
		secrets, err := s.Store.Secrets().ListByProject(ctx, sc.TenantID(), p.ID)
		if err != nil {
			return err
		}
		if len(secrets) > 0 {
			return domain.Conflict("cannot change the AWS connection while the workspace has secrets (project %q)", p.Slug)
		}
	}
	return nil
}

// ---------- Access tokens ----------

type CreateTokenInput struct {
	Name          string `json:"name"`
	ReadOnly      bool   `json:"read_only"`
	ExpiresInDays int    `json:"expires_in_days"` // 0 = never
}

type CreatedToken struct {
	domain.AccessToken
	Token string `json:"token"` // shown only once
}

func (s *Service) CreateAccessToken(ctx context.Context, sc *Scope, in CreateTokenInput) (*CreatedToken, error) {
	if sc.TokenID != "" {
		return nil, domain.Forbidden("access tokens cannot create other tokens; sign in on the web")
	}
	if err := sc.can(domain.RoleViewer, false); err != nil {
		return nil, err
	}
	in.Name = strings.TrimSpace(in.Name)
	if in.Name == "" {
		return nil, domain.Invalid("name is required")
	}
	if in.ExpiresInDays < 0 || in.ExpiresInDays > 3650 {
		return nil, domain.Invalid("expires_in_days must be between 0 and 3650")
	}
	raw := randomToken(domain.AccessTokenPrefix)
	t := &domain.AccessToken{
		ID: newID(), UserID: sc.UserID(), TenantID: sc.TenantID(), Name: in.Name,
		Prefix: raw[:len(domain.AccessTokenPrefix)+6], Hash: hashToken(raw),
		ReadOnly: in.ReadOnly || sc.Role == domain.RoleViewer, CreatedAt: now(),
	}
	if in.ExpiresInDays > 0 {
		exp := now().AddDate(0, 0, in.ExpiresInDays)
		t.ExpiresAt = &exp
	}
	if err := s.Store.Tokens().Create(ctx, t); err != nil {
		return nil, err
	}
	return &CreatedToken{AccessToken: *t, Token: raw}, nil
}

func (s *Service) ListAccessTokens(ctx context.Context, p *Principal) ([]domain.AccessToken, error) {
	return s.Store.Tokens().List(ctx, p.User.ID)
}

func (s *Service) DeleteAccessToken(ctx context.Context, p *Principal, id string) error {
	return s.Store.Tokens().Delete(ctx, p.User.ID, id)
}
